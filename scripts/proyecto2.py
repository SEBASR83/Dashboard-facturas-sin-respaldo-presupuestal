import pandas as pd

df = pd.read_excel("BASE.xlsx", sheet_name="Hoja1")
col = "VALOR DE LA FACTURA"

q1 = df[col].quantile(0.25)
q3 = df[col].quantile(0.75)
iqr = q3 - q1
limite_superior = q3 + 1.5 * iqr

atipicos = df[df[col] > limite_superior]

print("Q1:", q1)
print("Q3:", q3)
print("IQR:", iqr)
print("Umbral superior:", limite_superior)
print("Registros por encima del umbral:", len(atipicos))
print("Valor máximo:", df[col].max())

