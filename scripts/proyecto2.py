# 2. Cantidad y valor de las facturas por BASE
print("2. Cantidad y valor total por BASE")
resumen_base = (
    df.groupby("BASE", dropna=False)
      .agg(
          cantidad=("VALOR DE LA FACTURA", "size"),
          valor_total=("VALOR DE LA FACTURA", "sum"),
          valor_promedio=("VALOR DE LA FACTURA", "mean"),
          valor_mediano=("VALOR DE LA FACTURA", "median")
      )
      .reset_index()
)

display(resumen_base)

# 3. Distribución temporal por año de radicación
print("3. Registros y valores por año de radicación")
resumen_anual = (
    df.groupby("AÑO RADICACIÓN", dropna=False)
      .agg(
          cantidad=("VALOR DE LA FACTURA", "size"),
          valor_total=("VALOR DE LA FACTURA", "sum")
      )
      .reset_index()
      .sort_values("AÑO RADICACIÓN")
)

display(resumen_anual)

